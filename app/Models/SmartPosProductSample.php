<?php

namespace App\Models;

use App\Traits\HasSubscription;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * One product sample of the smart checkout vector gallery (Phase 3).
 *
 * Deliberately anemic: the model declares the table, the casts, the relations and
 * the query scopes. Every business rule (which tenant the row belongs to, the ten
 * samples per product, the L2 normalisation, where the crop is written) lives in
 * SmartCheckoutGalleryService.
 *
 * `embedding` is a raw binary buffer (little-endian float32) and is **never**
 * cast: serialising it to JSON would break the encoder (it is not valid UTF-8).
 * Read it through SmartCheckoutGalleryService, which base64-encodes it for the
 * browser, and never return a model of this class straight from a controller.
 */
class SmartPosProductSample extends Model
{
    use HasSubscription;

    /** Captured from a photo of the product in the catalog. */
    public const SOURCE_CATALOG_IMAGE = 'catalog_image';

    /** Captured from a scan at the cashier desk. */
    public const SOURCE_BARCODE_SCAN = 'barcode_scan';

    /** Captured while registering a product on the fly. */
    public const SOURCE_QUICK_REGISTER = 'quick_register';

    /** Captured from a cashier correction of a wrong recognition. */
    public const SOURCE_CASHIER_CORRECTION = 'cashier_correction';

    /** Every accepted `source`. */
    public const SOURCES = [
        self::SOURCE_CATALOG_IMAGE,
        self::SOURCE_BARCODE_SCAN,
        self::SOURCE_QUICK_REGISTER,
        self::SOURCE_CASHIER_CORRECTION,
    ];

    protected $table = 'smartpos_product_samples';

    protected $fillable = [
        'subscription_id',
        'branch_id',
        'product_id',
        'model_version',
        'embedding',
        'dim',
        'source',
        'crop_path',
        'quality',
    ];

    protected function casts(): array
    {
        return [
            'dim' => 'integer',
            // A decimal cast would hand back a string; the gallery API exposes a
            // number between 0 and 1.
            'quality' => 'float',
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | RELACIONES
    |--------------------------------------------------------------------------
    */

    public function subscription(): BelongsTo
    {
        return $this->belongsTo(Subscription::class);
    }

    public function branch(): BelongsTo
    {
        return $this->belongsTo(Branch::class);
    }

    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class);
    }

    /*
    |--------------------------------------------------------------------------
    | SCOPES
    |--------------------------------------------------------------------------
    */

    /**
     * Samples of one tenant: the scope of the gallery the browser downloads.
     */
    public function scopeForSubscription(Builder $query, int $subscriptionId): Builder
    {
        return $query->where('subscription_id', $subscriptionId);
    }

    /**
     * Samples generated by one model version.
     */
    public function scopeForModelVersion(Builder $query, string $modelVersion): Builder
    {
        return $query->where('model_version', $modelVersion);
    }

    /*
    |--------------------------------------------------------------------------
    | HELPERS
    |--------------------------------------------------------------------------
    */

    /**
     * Size in bytes of the stored buffer (should always be `dim * 4`).
     */
    public function embeddingBytes(): int
    {
        $embedding = $this->getAttributes()['embedding'] ?? '';

        return is_string($embedding) ? strlen($embedding) : 0;
    }
}
